<?php
/**
 * build-theme.php — copy the shared design system into the WordPress theme.
 *
 * The portfolio site is the single source of truth. This script:
 *   1. concatenates the six CSS layer files (in cascade order) into
 *      wordpress-theme/assets/css/design-system.css,
 *   2. copies the reusable JS modules into wordpress-theme/assets/js/,
 *   3. copies the SVG icon sprite into wordpress-theme/template-parts/.
 *
 * Run from the project root after changing shared CSS or JS:
 *   php tools/build-theme.php
 */

declare(strict_types=1);

$root  = dirname(__DIR__);
$site  = $root . '/public/assets';
$theme = $root . '/wordpress-theme';

$cssFiles  = ['tokens', 'reset', 'base', 'layout', 'components', 'utilities'];
$jsModules = ['theme', 'nav', 'reveal', 'video-facade', 'video-player'];

/** Copy a file, creating the target directory if needed. */
function copy_file(string $from, string $to): void
{
    if (!is_dir(dirname($to)) && !mkdir(dirname($to), 0755, true)) {
        throw new RuntimeException("Cannot create directory for {$to}");
    }
    if (!copy($from, $to)) {
        throw new RuntimeException("Cannot copy {$from}");
    }
    echo '  ', basename($to), PHP_EOL;
}

echo "CSS:", PHP_EOL;
$css = "/* GENERATED by tools/build-theme.php from public/assets/css/. Do not edit. */\n\n";
foreach ($cssFiles as $name) {
    $css .= file_get_contents("{$site}/css/{$name}.css") . "\n";
}
if (!is_dir("{$theme}/assets/css")) {
    mkdir("{$theme}/assets/css", 0755, true);
}
file_put_contents("{$theme}/assets/css/design-system.css", $css);
echo "  design-system.css (", round(strlen($css) / 1024, 1), " KB)", PHP_EOL;

echo "JS:", PHP_EOL;
foreach ($jsModules as $name) {
    copy_file("{$site}/js/{$name}.js", "{$theme}/assets/js/{$name}.js");
}

echo "Templates:", PHP_EOL;
copy_file("{$root}/src/templates/partials/icons.php", "{$theme}/template-parts/icons.php");

echo "Done.", PHP_EOL;
